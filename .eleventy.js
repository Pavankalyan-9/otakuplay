/**
 * OtakuPlay build.
 *
 * The catalogue itself (data.js, app.js, style.css, sw.js, icons) is plain static
 * output — Eleventy only assembles the pages around it, so the shell lives in one
 * place instead of being copy-pasted into five files.
 *
 * Links and asset paths are relative and depth-aware (`root`), so the same build
 * works at a domain root, under /otakuplay/ on GitHub Pages, and from a local
 * static server, with no pathPrefix juggling.
 */
export default function (eleventyConfig) {
  ['app.js', 'data.js', 'style.css', 'sw.js', 'manifest.json', 'icons'].forEach(file =>
    eleventyConfig.addPassthroughCopy({ [file]: file }));
  // Generated by scripts/build-vendor.mjs, which runs before this build.
  eleventyConfig.addPassthroughCopy({ 'src/vendor': 'vendor' });

  // "" for the root page, "../" one level down, and so on.
  eleventyConfig.addGlobalData('eleventyComputed', {
    root: data => {
      const depth = (data.page.url.match(/\//g) || []).length - 1;
      return depth > 0 ? '../'.repeat(depth) : '';
    },
  });

  eleventyConfig.addFilter('absoluteUrl', (path, base) =>
    new URL(path.replace(/^\//, ''), base.endsWith('/') ? base : `${base}/`).href);

  /* Nunjucks's `selectattr(attr, 'equalto', value)` silently returns the whole
     list unfiltered here rather than throwing — a real trap, not a typo — so
     every hub lookup runs as plain JS instead of trusting template-side
     filtering. This was shipping wrong decade/genre/sibling links on every
     entry and hub page (e.g. a game linking to an anime decade hub) before
     it was caught. */
  eleventyConfig.addFilter('findHub', (list, sect, slug) =>
    (list || []).find(h => h.sect === sect && h.slug === slug) || null);
  eleventyConfig.addFilter('findFranchiseHub', (list, heading) =>
    (list || []).find(h => h.heading === heading) || null);
  eleventyConfig.addFilter('hubSiblings', (list, sect, excludeSlug) =>
    (list || []).filter(h => h.sect === sect && h.slug !== excludeSlug));

  return {
    dir: {
      input: 'src',
      output: '_site',
      includes: '_includes',
      data: '_data',
    },
    markdownTemplateEngine: 'njk',
    htmlTemplateEngine: 'njk',
  };
}
